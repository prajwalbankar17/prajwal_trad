"""Seed reference data: permissions, roles, the first admin, strategies,
a default risk profile, portfolio and the trading-module switches.

Idempotent - safe to re-run. It never overwrites an existing user's password
and never deletes anything.

The admin password is taken from ADMIN_PASSWORD if set; otherwise a strong one
is generated and written to `backend/.seed_admin_credentials.txt` (gitignored,
mode 600). It is not printed to the console or to logs.
"""

from __future__ import annotations

import os
import secrets
import string
import sys
from pathlib import Path

from sqlalchemy import select

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.config import settings  # noqa: E402
from app.core.permissions import PERMISSIONS, ROLE_SEEDS  # noqa: E402
from app.core.security import hash_password  # noqa: E402
from app.db.session import session_scope  # noqa: E402
from app.models.instrument import ExchangeRef, Sector  # noqa: E402
from app.models.portfolio import Portfolio  # noqa: E402
from app.models.risk import RiskProfile  # noqa: E402
from app.models.strategy import Strategy, StrategyVersion, TradingModuleState  # noqa: E402
from app.models.system import Permission, Role, User  # noqa: E402
from app.strategies.registry import STRATEGY_SEEDS  # noqa: E402

CREDENTIALS_FILE = Path(__file__).resolve().parents[1] / ".seed_admin_credentials.txt"

EXCHANGES = [
    ("NSE", "National Stock Exchange of India"),
    ("BSE", "BSE Limited"),
    ("NFO", "NSE Futures & Options"),
    ("BFO", "BSE Futures & Options"),
]

SECTORS = [
    "Automobile", "Banking", "Capital Goods", "Cement", "Chemicals",
    "Construction", "Consumer Durables", "FMCG", "Healthcare", "Infrastructure",
    "Information Technology", "Media", "Metals & Mining", "Oil & Gas",
    "Pharmaceuticals", "Power", "Realty", "Services", "Telecom", "Textiles",
    "Financial Services", "Insurance", "Diversified",
]


def generate_password(length: int = 20) -> str:
    alphabet = string.ascii_letters + string.digits + "!@#$%^&*-_=+"
    while True:
        pw = "".join(secrets.choice(alphabet) for _ in range(length))
        if (
            any(c.islower() for c in pw)
            and any(c.isupper() for c in pw)
            and any(c.isdigit() for c in pw)
            and any(not c.isalnum() for c in pw)
        ):
            return pw


def seed_permissions(db) -> dict[str, Permission]:
    existing = {p.code: p for p in db.scalars(select(Permission)).all()}
    for spec in PERMISSIONS:
        perm = existing.get(spec.code)
        if perm is None:
            perm = Permission(
                code=spec.code,
                resource=spec.resource,
                action=spec.action,
                description=spec.description,
                is_sensitive=spec.is_sensitive,
            )
            db.add(perm)
            existing[spec.code] = perm
        else:
            perm.description = spec.description
            perm.is_sensitive = spec.is_sensitive
    db.flush()
    print(f"  permissions: {len(existing)}")
    return existing


def seed_roles(db, perms: dict[str, Permission]) -> dict[str, Role]:
    roles: dict[str, Role] = {r.name: r for r in db.scalars(select(Role)).all()}
    for name, spec in ROLE_SEEDS.items():
        role = roles.get(name)
        if role is None:
            role = Role(
                name=name,
                description=spec["description"],
                is_system=True,
                priority=spec["priority"],
            )
            db.add(role)
            roles[name] = role
            db.flush()
        # System roles keep their canonical permission set; custom roles are
        # left untouched.
        if role.is_system:
            role.permissions = [perms[c] for c in sorted(spec["permissions"]) if c in perms]
    db.flush()
    print(f"  roles: {len(roles)} ({', '.join(sorted(roles))})")
    return roles


def seed_admin(db, roles: dict[str, Role]) -> None:
    email = os.getenv("ADMIN_EMAIL", "admin@local").lower()
    username = os.getenv("ADMIN_USERNAME", "admin")

    if db.scalar(select(User).where(User.username == username)):
        print(f"  admin user '{username}' already exists - password unchanged")
        return

    password = os.getenv("ADMIN_PASSWORD") or generate_password()
    user = User(
        email=email,
        username=username,
        full_name="Platform Administrator",
        hashed_password=hash_password(password),
        is_superuser=True,
        is_active=True,
    )
    user.roles.append(roles["Super Admin"])
    db.add(user)
    db.flush()

    if not os.getenv("ADMIN_PASSWORD"):
        CREDENTIALS_FILE.write_text(
            "Generated by scripts/seed.py - delete this file after you have "
            "stored the password in your password manager.\n"
            f"username: {username}\n"
            f"email: {email}\n"
            f"password: {password}\n"
        )
        CREDENTIALS_FILE.chmod(0o600)
        print(f"  admin user created - credentials written to {CREDENTIALS_FILE}")
    else:
        print(f"  admin user '{username}' created with ADMIN_PASSWORD from the environment")


def seed_reference(db) -> None:
    have_ex = {e.code for e in db.scalars(select(ExchangeRef)).all()}
    for code, name in EXCHANGES:
        if code not in have_ex:
            db.add(ExchangeRef(code=code, name=name))

    have_sec = {s.name for s in db.scalars(select(Sector)).all()}
    for name in SECTORS:
        if name not in have_sec:
            db.add(Sector(name=name))
    db.flush()
    print(f"  exchanges: {len(EXCHANGES)}, sectors: {len(SECTORS)}")


def seed_strategies(db) -> None:
    existing = {s.code: s for s in db.scalars(select(Strategy)).all()}
    created = 0
    for spec in STRATEGY_SEEDS:
        strategy = existing.get(spec["code"])
        if strategy is None:
            strategy = Strategy(
                code=spec["code"],
                name=spec["name"],
                category=spec["category"],
                module=spec.get("module", "EQUITY"),
                description=spec["description"],
                is_active=False,            # nothing trades until a human enables it
                is_research_only=True,
                default_timeframe=spec.get("default_timeframe", "5m"),
                supported_timeframes=spec.get("supported_timeframes", []),
                default_parameters=spec.get("default_parameters", {}),
                parameter_schema=spec.get("parameter_schema", {}),
            )
            db.add(strategy)
            db.flush()
            version = StrategyVersion(
                strategy_id=strategy.id,
                version=1,
                parameters=spec.get("default_parameters", {}),
                changelog="Initial seeded version.",
            )
            db.add(version)
            db.flush()
            strategy.current_version_id = version.id
            created += 1
        else:
            strategy.name = spec["name"]
            strategy.description = spec["description"]
            strategy.parameter_schema = spec.get("parameter_schema", {})
    db.flush()
    print(f"  strategies: {len(STRATEGY_SEEDS)} defined, {created} newly created")


def seed_risk_and_portfolio(db) -> None:
    profile = db.scalar(select(RiskProfile).where(RiskProfile.is_default.is_(True)))
    if profile is None:
        profile = RiskProfile(
            name="Default Paper Profile",
            description="Conservative starting limits for paper trading research.",
            is_default=True,
            capital=settings.DEFAULT_CAPITAL,
            max_risk_per_trade_pct=settings.MAX_RISK_PER_TRADE_PCT,
            max_daily_loss_pct=settings.MAX_DAILY_LOSS_PCT,
            max_open_positions=settings.MAX_OPEN_POSITIONS,
            max_trades_per_day=settings.MAX_TRADES_PER_DAY,
            max_capital_utilisation_pct=settings.MAX_CAPITAL_UTILISATION_PCT,
        )
        db.add(profile)
        db.flush()
        print("  risk profile: created 'Default Paper Profile'")

    admin = db.scalar(select(User).where(User.is_superuser.is_(True)))
    if admin and not db.scalar(select(Portfolio).where(Portfolio.user_id == admin.id)):
        db.add(
            Portfolio(
                user_id=admin.id,
                name="Paper Portfolio",
                description="Default paper-trading portfolio.",
                execution_mode="PAPER",
                risk_profile_id=profile.id,
                starting_capital=settings.DEFAULT_CAPITAL,
                current_capital=settings.DEFAULT_CAPITAL,
                available_capital=settings.DEFAULT_CAPITAL,
                is_default=True,
            )
        )
        print("  portfolio: created 'Paper Portfolio'")
    db.flush()


def seed_module_states(db) -> None:
    for module in ("EQUITY", "FNO"):
        if not db.scalar(select(TradingModuleState).where(TradingModuleState.module == module)):
            db.add(
                TradingModuleState(
                    module=module,
                    is_active=False,              # both start inactive, by design
                    monitor_open_positions=True,
                    reason="Seeded inactive. Activate explicitly from the UI.",
                )
            )
    db.flush()
    print("  trading modules: EQUITY and FNO seeded (both inactive)")


def main() -> None:
    print("Seeding reference data...")
    with session_scope() as db:
        perms = seed_permissions(db)
        roles = seed_roles(db, perms)
        seed_admin(db, roles)
        seed_reference(db)
        seed_strategies(db)
        seed_risk_and_portfolio(db)
        seed_module_states(db)
    print("Done.")


if __name__ == "__main__":
    main()
